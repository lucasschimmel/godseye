import {
  AgentChatEvent,
  AgentChatEvents,
  CONTROL_API_VERSION,
  HttpId,
  LOCAL_DEFAULTS,
} from "@godseye/contracts";
import { type Actor, type AgentEngine, DomainError } from "@godseye/core";
import type { Hono } from "hono";
import type { ControlEnvironment } from "./api-types.js";

export const CHAT_STREAM_DEFAULTS = {
  maxConnections: 4,
  perConversation: 2,
  lifetimeMs: 60000,
  pollMs: 200,
  reauthenticateMs: 1000,
  idleConsumerMs: 5000,
  heartbeatMs: 10000,
} as const;
export type ChatStreamOptions = { [K in keyof typeof CHAT_STREAM_DEFAULTS]?: number };

function cursorFor(url: string, header?: string) {
  const query = new URL(url).searchParams;
  if ([...query.keys()].some((k) => k !== "after") || query.getAll("after").length > 1)
    throw new DomainError("INVALID_INPUT", "Invalid chat stream query", 422);
  const candidate = header ?? query.get("after") ?? "0";
  if (!/^(0|[1-9][0-9]{0,15})$/.test(candidate) || !Number.isSafeInteger(Number(candidate)))
    throw new DomainError("INVALID_INPUT", "Invalid chat stream cursor", 422);
  return Number(candidate);
}

/** Owner stream lifetime is independent of the model task and its physical admission. */
export function registerAgentChatTransport(
  app: Hono<ControlEnvironment>,
  engine: AgentEngine,
  authenticate: (headers: Headers) => Promise<Actor | null>,
  options: ChatStreamOptions = {},
) {
  const policy = { ...CHAT_STREAM_DEFAULTS, ...options };
  for (const value of Object.values(policy))
    if (!Number.isSafeInteger(value) || value < 1) throw new Error("Invalid chat stream policy");
  const live = new Map<string, number>();
  let connections = 0;
  const base = `${LOCAL_DEFAULTS.apiBase}/agents`;
  app.get(`${base}/artifacts/:id/download`, async (c) => {
    const artifact = await engine.chatArtifact(c.get("actor"), HttpId.parse(c.req.param("id")));
    // The name is display metadata; the download name is always generated by the server.
    return c.body(artifact.content, 200, {
      "Content-Type": "text/plain; charset=utf-8",
      "Content-Disposition": `attachment; filename="artifact-${artifact.id}.txt"`,
      "X-Content-Type-Options": "nosniff",
      "Content-Security-Policy": "sandbox; default-src 'none'",
      "Cache-Control": "private, no-store",
    });
  });
  app.get(`${base}/conversations/:id/events`, async (c) => {
    const id = HttpId.parse(c.req.param("id"));
    let cursor = cursorFor(c.req.url, c.req.header("last-event-id"));
    const actor = c.get("actor");
    // Authenticate and validate existence/cursor before publishing successful stream headers.
    const initial = AgentChatEvents.parse(await engine.chatEvents(actor, id, cursor));
    if (connections >= policy.maxConnections || (live.get(id) ?? 0) >= policy.perConversation)
      throw new DomainError("CAPACITY_EXCEEDED", "Owner chat stream capacity reached", 429);
    connections++;
    live.set(id, (live.get(id) ?? 0) + 1);
    const encoder = new TextEncoder();
    let closed = false,
      pulling = false,
      ready = false,
      lastRead = Date.now(),
      lastAuth = 0,
      lastHeartbeat = Date.now();
    let page = initial;
    let offset = 0;
    let output: ReadableStreamDefaultController<Uint8Array> | undefined;
    let timer: ReturnType<typeof setInterval> | undefined;
    let deadline: ReturnType<typeof setTimeout> | undefined;
    let wake: (() => void) | undefined;
    let verification: Promise<void> | undefined;
    const release = () => {
      if (closed) return;
      closed = true;
      connections--;
      const remaining = (live.get(id) ?? 1) - 1;
      if (remaining) live.set(id, remaining);
      else live.delete(id);
      if (timer) clearInterval(timer);
      if (deadline) clearTimeout(deadline);
      c.req.raw.signal.removeEventListener("abort", close);
      wake?.();
    };
    const close = () => {
      if (closed) return;
      release();
      try {
        output?.close();
      } catch {
        /* The consumer may already have cancelled. */
      }
    };
    const frame = (event: string, data: unknown, sequence?: number) =>
      encoder.encode(
        `${sequence === undefined ? "" : `id: ${sequence}\n`}event: ${event}\ndata: ${JSON.stringify(data)}\n\n`,
      );
    const verify = () => {
      if (!verification) {
        verification = (async () => {
          const owner = await authenticate(c.req.raw.headers);
          if (
            owner?.kind !== "owner" ||
            owner.id !== actor.id ||
            owner.sessionId !== actor.sessionId
          )
            throw new Error("Owner stream authority changed");
          lastAuth = Date.now();
        })().finally(() => {
          verification = undefined;
        });
      }
      return verification;
    };
    const stream = new ReadableStream<Uint8Array>({
      start(controller) {
        output = controller;
        c.req.raw.signal.addEventListener("abort", close, { once: true });
        deadline = setTimeout(close, policy.lifetimeMs);
        timer = setInterval(() => {
          if (!pulling && Date.now() - lastRead >= policy.idleConsumerMs) close();
          else if (Date.now() - lastAuth >= policy.reauthenticateMs) void verify().catch(close);
        }, policy.reauthenticateMs);
        if (c.req.raw.signal.aborted) close();
      },
      async pull(controller) {
        if (closed || pulling) return;
        pulling = true;
        lastRead = Date.now();
        try {
          await verify();
          if (closed) return;
          if (!ready) {
            ready = true;
            controller.enqueue(frame("ready", { version: CONTROL_API_VERSION, cursor }));
            return;
          }
          while (!closed) {
            if (page.reset) {
              cursor = page.cursor;
              page = { reset: false, cursor, events: [] };
              offset = 0;
              controller.enqueue(frame("reset", { cursor }, cursor));
              return;
            }
            const event = page.events[offset++];
            if (event) {
              const value = AgentChatEvent.parse(event);
              if (value.conversationId !== id || value.cursor !== cursor + 1)
                throw new Error("Chat stream journal mapping changed");
              cursor = value.cursor;
              controller.enqueue(frame("chat", value, cursor));
              return;
            }
            if (Date.now() - lastHeartbeat >= policy.heartbeatMs) {
              lastHeartbeat = Date.now();
              controller.enqueue(encoder.encode(": heartbeat\n\n"));
              return;
            }
            await new Promise<void>((done) => {
              const wait = setTimeout(() => {
                wake = undefined;
                done();
              }, policy.pollMs);
              wake = () => {
                clearTimeout(wait);
                wake = undefined;
                done();
              };
            });
            if (closed) return;
            await verify();
            page = AgentChatEvents.parse(await engine.chatEvents(actor, id, cursor));
            offset = 0;
          }
        } catch {
          // A closed stream requests a safe authenticated refetch; no private diagnostic escapes.
          close();
        } finally {
          pulling = false;
        }
      },
      cancel() {
        release();
      },
    });
    return new Response(stream, {
      headers: {
        "Content-Type": "text/event-stream; charset=utf-8",
        "Cache-Control": "private, no-store",
        "X-Accel-Buffering": "no",
        "X-Content-Type-Options": "nosniff",
      },
    });
  });
}
