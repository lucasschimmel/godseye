#!/usr/bin/env bash
# g03-work-egress.sh - outbound allowlist for the work VM (Jenkins agent), rollback-safe (DS04, DS13).
#
#   bash g03-work-egress.sh apply     install dnsmasq-base, load the egress table, arm a 5-minute rollback
#   bash g03-work-egress.sh verify    allowed names answer, everything else is refused (run before commit)
#   bash g03-work-egress.sh commit    disarm the rollback and make the change persistent
#   bash g03-work-egress.sh refresh   rebuild the resolver configuration after editing the domain lists
#   bash g03-work-egress.sh rollback  restore the open egress and the previous resolver setup now
#
# How it works: a local dnsmasq (godseye-egress-dns.service, 127.0.0.1:53, upstream the Hetzner
# resolvers) copies every address it resolves for an allowlisted domain into the nftables set
# `allowed4` of table `inet godseye_egress`. The output chain (policy drop) lets only the dnsmasq
# user reach the upstream resolvers, allows NTP, ICMP and established flows, and accepts TCP 22/80/443
# solely towards addresses in `allowed4`. Everything else, including IPv6 and DNS to any other
# resolver, is refused. AAAA answers are filtered so clients use IPv4. Inbound traffic is governed by
# g01-guest-firewall.sh (SSH from the Jenkins controller). systemd-resolved stays running with its stub
# listener off; /etc/resolv.conf points to 127.0.0.1.
# Known limit: DNS to the allowed upstream resolvers is unrestricted, so DNS tunnelling is not blocked.
# Domains: work-egress-domains.txt (repository) plus /etc/godseye/work-egress-domains.local and the
# guest's configured apt mirrors. Rollback copy: /var/lib/godseye/rollback/g03-<timestamp>/.
set -euo pipefail
umask 022

MODE="${1:-}"
TS="$(date -u +%Y%m%dT%H%M%SZ)"
RB="/var/lib/godseye/rollback/g03-$TS"
HERE="$(cd "$(dirname "$0")" && pwd)"
LIB=/usr/local/lib/godseye
ETC=/etc/godseye
NFT_CONF="$ETC/work-egress.nft"
DNS_CONF="$ETC/work-egress-dnsmasq.conf"
DOMAINS_REPO="$ETC/work-egress-domains.txt"
DOMAINS_LOCAL="$ETC/work-egress-domains.local"
DNS_UNIT=/etc/systemd/system/godseye-egress-dns.service
FW_UNIT=/etc/systemd/system/godseye-egress-fw.service
RESOLVED_DROPIN=/etc/systemd/resolved.conf.d/20-godseye-no-stub.conf
ROLLBACK_UNIT=g03-egress-rollback
WAIT="${GODSEYE_ROLLBACK_SECONDS:-300}"
UPSTREAM_DNS="${GODSEYE_UPSTREAM_DNS:-185.12.64.1 185.12.64.2}"
DNS_USER=dnsmasq

collect_domains() {
  {
    sed -e 's/#.*//' -e 's/[[:space:]]//g' "$DOMAINS_REPO"
    [ -f "$DOMAINS_LOCAL" ] && sed -e 's/#.*//' -e 's/[[:space:]]//g' "$DOMAINS_LOCAL"
    # Hosts of the apt mirror lists and sources configured on this guest.
    grep -hE '^https?://' /etc/apt/mirrors/*.list 2>/dev/null || true
    grep -hE '^URIs:' /etc/apt/sources.list.d/*.sources 2>/dev/null | sed 's/^URIs:[[:space:]]*//' | tr ' ' '\n' | grep -E '^https?://' || true
    grep -hE '^deb ' /etc/apt/sources.list 2>/dev/null | awk '{print $2}' | grep -E '^https?://' || true
  } | sed -E 's#^https?://##; s#[/:].*$##' | grep -E '^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$' | sort -u
}

render_dns_conf() {
  {
    echo "# Generated by g03-work-egress.sh; do not edit (edit the domain lists and run refresh)."
    echo "listen-address=127.0.0.1"
    echo "bind-interfaces"
    echo "port=53"
    echo "no-resolv"
    echo "no-hosts"
    echo "cache-size=0"
    echo "filter-AAAA"
    echo "pid-file="
    echo "user=$DNS_USER"
    for ns in $UPSTREAM_DNS; do echo "server=$ns"; done
    collect_domains | while read -r domain; do
      echo "nftset=/${domain}/4#inet#godseye_egress#allowed4"
    done
  }
}

render_nft() {
  cat <<NFT
add table inet godseye_egress
delete table inet godseye_egress
table inet godseye_egress {
	set allowed4 {
		type ipv4_addr
		flags timeout
		timeout 6h
		size 8192
	}
	chain output {
		type filter hook output priority filter; policy drop;
		oif "lo" accept
		ct state established,related accept
		ct state invalid drop
		ip protocol icmp accept
		meta l4proto ipv6-icmp accept
		udp dport 123 accept comment "NTP (chrony)"
		meta skuid "$DNS_USER" ip daddr { $(echo "$UPSTREAM_DNS" | sed 's/ /, /g') } udp dport 53 accept comment "resolver upstream"
		meta skuid "$DNS_USER" ip daddr { $(echo "$UPSTREAM_DNS" | sed 's/ /, /g') } tcp dport 53 accept comment "resolver upstream"
		ip daddr @allowed4 tcp dport { 22, 80, 443 } accept comment "allowlisted names resolved by the local dnsmasq"
		ip daddr 10.20.1.10 tcp dport 5000 accept comment "private image registry on the pro VM (app build agent pushes)"
		counter reject with icmpx type admin-prohibited
	}
}
NFT
}

install_files() {
  command -v /usr/sbin/dnsmasq >/dev/null 2>&1 || DEBIAN_FRONTEND=noninteractive apt-get install -y dnsmasq-base
  /usr/sbin/dnsmasq --version | grep -q nftset || { echo "dnsmasq lacks nftset support" >&2; exit 1; }
  command -v nft >/dev/null 2>&1 || DEBIAN_FRONTEND=noninteractive apt-get install -y nftables
  systemctl disable --now nftables.service 2>/dev/null || true
  id "$DNS_USER" >/dev/null 2>&1 || adduser --system --no-create-home --group --shell /usr/sbin/nologin "$DNS_USER"
  install -d -m 0755 "$ETC" "$LIB" /etc/systemd/resolved.conf.d
  install -m 0644 "$HERE/work-egress-domains.txt" "$DOMAINS_REPO"
  [ -f "$DOMAINS_LOCAL" ] || : >"$DOMAINS_LOCAL"
  install -m 0755 "$0" "$LIB/g03-work-egress.sh"
  # work-egress-domains.txt travels with the script so a later refresh does not need the repository.
  render_dns_conf >"$DNS_CONF"
  render_nft >"$NFT_CONF"
  nft -c -f "$NFT_CONF"
  /usr/sbin/dnsmasq --test --conf-file="$DNS_CONF"
  cat >"$DNS_UNIT" <<EOF
[Unit]
Description=G.O.D.S.E.Y.E work VM egress DNS (dnsmasq filling nftables set allowed4)
After=godseye-egress-fw.service
Wants=godseye-egress-fw.service

[Service]
ExecStart=/usr/sbin/dnsmasq --keep-in-foreground --conf-file=$DNS_CONF
Restart=on-failure
RestartSec=2s

[Install]
WantedBy=multi-user.target
EOF
  cat >"$FW_UNIT" <<EOF
[Unit]
Description=G.O.D.S.E.Y.E work VM egress allowlist (table inet godseye_egress)
DefaultDependencies=no
Before=network-pre.target
Wants=network-pre.target
After=local-fs.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/sbin/nft -f $NFT_CONF
ExecStop=-/usr/sbin/nft delete table inet godseye_egress

[Install]
WantedBy=multi-user.target
EOF
  cat >"$RESOLVED_DROPIN" <<'EOF'
[Resolve]
DNSStubListener=no
EOF
  systemctl daemon-reload
}

point_resolver_local() {
  systemctl restart systemd-resolved.service
  systemctl restart godseye-egress-dns.service
  sleep 1
  rm -f /etc/resolv.conf
  printf 'nameserver 127.0.0.1\noptions edns0\n' >/etc/resolv.conf
}

restore_resolver() {
  systemctl stop godseye-egress-dns.service 2>/dev/null || true
  rm -f "$RESOLVED_DROPIN"
  rm -f /etc/resolv.conf
  ln -s /run/systemd/resolve/stub-resolv.conf /etc/resolv.conf
  systemctl restart systemd-resolved.service
}

fetch() { # url expected-class; prints the HTTP status or 000
  curl -sS -o /dev/null -m 15 --connect-timeout 8 -w '%{http_code}' "$1" 2>/dev/null || true
}

case "$MODE" in
  apply)
    mkdir -p "$RB"
    nft list ruleset >"$RB/ruleset-before.nft"
    readlink /etc/resolv.conf >"$RB/resolv-link" 2>/dev/null || cp -a /etc/resolv.conf "$RB/resolv.conf"
    install_files
    systemctl stop "$ROLLBACK_UNIT.timer" "$ROLLBACK_UNIT.service" 2>/dev/null || true
    # Armed BEFORE the change: if nothing disarms it, the previous egress and resolver come back.
    systemd-run --quiet --unit="$ROLLBACK_UNIT" --on-active="$WAIT" bash "$LIB/g03-work-egress.sh" rollback
    nft -f "$NFT_CONF"
    point_resolver_local
    echo "WORK_EGRESS_APPLIED rollback armed in ${WAIT}s; run: $0 verify, test the Jenkins agent, then: $0 commit"
    ;;
  verify)
    fail=0
    for url in https://github.com https://registry.npmjs.org/bun https://pypi.org/simple/ https://deb.debian.org/debian/; do
      code="$(fetch "$url")"
      case "$code" in 2??|3??|4??) echo "ALLOWED_OK $url -> $code" ;; *) echo "ALLOWED_FAIL $url -> $code"; fail=1 ;; esac
    done
    for url in https://example.com https://1.1.1.1 https://www.google.com http://neverssl.com; do
      code="$(fetch "$url")"
      case "$code" in 000) echo "BLOCKED_OK $url" ;; *) echo "BLOCKED_FAIL $url -> $code"; fail=1 ;; esac
    done
    if timeout 5 bash -c 'exec 3<>/dev/tcp/8.8.8.8/53' 2>/dev/null; then echo "BLOCKED_FAIL direct DNS (tcp) to 8.8.8.8"; fail=1; else echo "BLOCKED_OK direct DNS (tcp) to 8.8.8.8"; fi
    if timeout 5 bash -c 'exec 3<>/dev/tcp/185.12.64.1/53' 2>/dev/null; then echo "BLOCKED_FAIL resolver reachable by non-dnsmasq users"; fail=1; else echo "BLOCKED_OK resolver only through dnsmasq"; fi
    if timeout 5 bash -c 'exec 3<>/dev/tcp/10.20.1.10/8080' 2>/dev/null; then echo "BLOCKED_FAIL pro:8080 reachable"; fail=1; else echo "BLOCKED_OK pro:8080"; fi
    nft list chain inet godseye_egress output | grep -E 'counter'
    nft list set inet godseye_egress allowed4 | grep -c 'expires' | sed 's/^/allowed4 entries: /'
    [ "$fail" -eq 0 ] && echo "WORK_EGRESS_VERIFY_PASS" || { echo "WORK_EGRESS_VERIFY_FAIL" >&2; exit 1; }
    ;;
  commit)
    nft list table inet godseye_egress >/dev/null
    systemctl is-active --quiet godseye-egress-dns.service
    systemctl stop "$ROLLBACK_UNIT.timer" "$ROLLBACK_UNIT.service" 2>/dev/null || true
    systemctl enable godseye-egress-fw.service godseye-egress-dns.service
    echo "WORK_EGRESS_COMMITTED (persistent; rollback: $LIB/g03-work-egress.sh rollback)"
    ;;
  refresh)
    render_dns_conf >"$DNS_CONF"
    /usr/sbin/dnsmasq --test --conf-file="$DNS_CONF"
    systemctl restart godseye-egress-dns.service
    echo "WORK_EGRESS_REFRESHED domains: $(grep -c '^nftset=' "$DNS_CONF")"
    ;;
  rollback)
    systemctl stop "$ROLLBACK_UNIT.timer" 2>/dev/null || true
    nft delete table inet godseye_egress 2>/dev/null || true
    restore_resolver
    systemctl disable godseye-egress-fw.service godseye-egress-dns.service 2>/dev/null || true
    echo "WORK_EGRESS_ROLLED_BACK"
    ;;
  *)
    echo "usage: $0 apply|verify|commit|refresh|rollback" >&2
    exit 64
    ;;
esac
